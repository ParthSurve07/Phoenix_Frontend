"use client";

import { useState } from "react";
import PredictionTable from "@/components/prediction/PredictionTable";
import RiskInsightCard from "@/components/risk/RiskInsightCard";
import RiskScoreBanner from "@/components/risk/RiskScoreBanner";
import { usePredictions } from "@/hooks/usePredictions";
import { useRisk, useAnalyzeRisk } from "@/hooks/useRisk";
import { Info, RefreshCw } from "lucide-react";
import { Button } from "@/components/ui/button";

function getSignalCounts(data) {
  return data.reduce(
    (acc, s) => {
      acc[s.signal] = (acc[s.signal] || 0) + 1;
      return acc;
    },
    { BUY: 0, SELL: 0, NEUTRAL: 0 }
  );
}

const tabs = ["Signals", "Risk Insights"];

export default function PredictionsPage() {
  const [activeTab, setActiveTab] = useState("Signals");

  const { data: predictions, isLoading: predictionsLoading } = usePredictions();
  const { data: risk, isLoading: riskLoading } = useRisk();
  const analyzeRisk = useAnalyzeRisk();

  const data = predictions || [];
  const counts = getSignalCounts(data);

  const lastComputed = data.length > 0
    ? new Date(data[0].generatedAt).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" })
    : "Not yet";

  return (
    <div className="flex flex-col gap-6 sm:gap-8">
      {/* Header */}
      <div>
        <h1 className="text-slate-900 text-xl sm:text-2xl md:text-3xl font-semibold mt-4">Predictions</h1>
        <p className="text-slate-500 text-sm sm:text-base mt-1 md:mt-2">
          ML-generated signals and risk analysis for your holdings
        </p>
      </div>

      {/* Tabs */}
      <div className="flex flex-wrap gap-1 bg-white border border-amber-200 rounded-lg p-1 w-full sm:w-fit">
        {tabs.map((tab) => (
          <button
            key={tab}
            onClick={() => setActiveTab(tab)}
            className={`flex-1 sm:flex-none px-4 py-2 sm:py-1.5 rounded-md text-sm font-medium transition-colors text-center ${activeTab === tab
              ? "bg-slate-900 text-white"
              : "text-slate-600 hover:bg-amber-50 hover:text-amber-700"
              }`}
          >
            {tab}
          </button>
        ))}
      </div>

      {/* SIGNALS TAB */}
      {activeTab === "Signals" && (
        <>
          {/* Summary Strip - Fixed to use the 2x2 grid pattern on mobile */}
          <div className="grid grid-cols-2 lg:grid-cols-4 gap-px bg-amber-200 border border-amber-200 rounded-xl overflow-hidden shadow-sm">
            <div className="bg-white p-4 sm:p-5 flex flex-col justify-center">
              <p className="text-slate-500 text-xs sm:text-sm">Buy Signals</p>
              <p className="text-green-600 font-semibold text-base sm:text-lg md:text-xl mt-0.5 sm:mt-1">{counts.BUY} stocks</p>
            </div>

            <div className="bg-white p-4 sm:p-5 flex flex-col justify-center">
              <p className="text-slate-500 text-xs sm:text-sm">Sell Signals</p>
              <p className="text-red-600 font-semibold text-base sm:text-lg md:text-xl mt-0.5 sm:mt-1">{counts.SELL} stocks</p>
            </div>

            <div className="bg-white p-4 sm:p-5 flex flex-col justify-center">
              <p className="text-slate-500 text-xs sm:text-sm">Neutral</p>
              <p className="text-amber-700 font-semibold text-base sm:text-lg md:text-xl mt-0.5 sm:mt-1">{counts.NEUTRAL} stocks</p>
            </div>

            <div className="bg-white p-4 sm:p-5 flex flex-col justify-center">
              <p className="text-slate-500 text-xs sm:text-sm">Last Computed</p>
              <p className="text-slate-900 font-semibold text-sm sm:text-base md:text-lg mt-0.5 sm:mt-1 truncate">{lastComputed}</p>
            </div>
          </div>

          <div className="flex items-start gap-2 bg-amber-50 border border-amber-200 rounded-lg px-4 py-3">
            <Info className="text-amber-700 mt-0.5 shrink-0 w-4 h-4 sm:w-[15px] sm:h-[15px]" />
            <p className="text-slate-600 text-xs sm:text-sm leading-relaxed">
              Signals are generated by XGBoost and Prophet models using historical price data.
              They are for informational purposes only and do not constitute financial advice.
            </p>
          </div>

          {predictionsLoading ? (
            <div className="bg-white border border-amber-200 rounded-xl p-6 sm:p-8 text-slate-400 text-sm text-center animate-pulse">Loading predictions...</div>
          ) : data.length === 0 ? (
            <div className="bg-white border border-amber-200 rounded-xl p-6 sm:p-8 text-slate-400 text-sm text-center">
              No predictions yet — they will appear after the ML service runs.
            </div>
          ) : (
            <PredictionTable data={data} />
          )}
        </>
      )}

      {/* RISK INSIGHTS TAB */}
      {activeTab === "Risk Insights" && (
        <>
          <div className="flex justify-end w-full sm:w-auto">
            {/* Added w-full on mobile for the button */}
            <Button
              className="bg-slate-900 hover:bg-slate-800 text-white text-sm gap-2 w-full sm:w-auto h-11 sm:h-10"
              onClick={() => analyzeRisk.mutate()}
              disabled={analyzeRisk.isPending}
            >
              <RefreshCw size={15} />
              {analyzeRisk.isPending ? "Analyzing..." : "Re-analyze Risk"}
            </Button>
          </div>

          {riskLoading ? (
            <div className="bg-white border border-amber-200 rounded-xl p-6 sm:p-8 text-slate-400 text-sm text-center animate-pulse">Loading risk analysis...</div>
          ) : !risk ? (
            <div className="bg-white border border-amber-200 rounded-xl py-8 px-4 flex flex-col items-center gap-4 text-center">
              <p className="text-slate-400 text-sm">No risk analysis yet.</p>
              <Button
                className="bg-slate-900 hover:bg-slate-800 text-white text-sm gap-2 w-full max-w-[200px] h-11 sm:h-10"
                onClick={() => analyzeRisk.mutate()}
                disabled={analyzeRisk.isPending}
              >
                <RefreshCw size={15} />
                {analyzeRisk.isPending ? "Analyzing..." : "Run Risk Analysis"}
              </Button>
            </div>
          ) : (
            <>
              <RiskScoreBanner data={risk} />
              {/* Tightened grid gap on mobile */}
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4 sm:gap-6">
                {risk.insights.map((insight, i) => (
                  <RiskInsightCard key={i} insight={insight} />
                ))}
              </div>
            </>
          )}
        </>
      )}
    </div>
  );
}