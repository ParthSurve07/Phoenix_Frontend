import PredictionTable from "@/components/prediction/PredictionTable";
import { mockPredictions } from "@/lib/mockData";
import { Info } from "lucide-react";

// Signal summary counts
function getSignalCounts(data) {
  return data.reduce(
    (acc, s) => {
      acc[s.signal] = (acc[s.signal] || 0) + 1;
      return acc;
    },
    { BUY: 0, SELL: 0, NEUTRAL: 0 }
  );
}

export default function PredictionsPage() {
  const counts = getSignalCounts(mockPredictions);

  return (
    <div className="flex flex-col gap-6">

      {/* Header */}
      <div>
        <h1 className="text-slate-900 text-xl font-semibold mt-4">Predictions</h1>
        <p className="text-slate-500 text-sm mt-1">
          ML-generated signals for your holdings
        </p>
      </div>

      {/* Signal Summary Strip */}
      <div className="bg-white border border-amber-200 rounded-xl px-6 py-4 flex gap-8">
        <div>
          <p className="text-slate-500 text-xs">Buy Signals</p>
          <p className="text-green-600 font-semibold text-lg mt-0.5">
            {counts.BUY} stocks
          </p>
        </div>
        <div className="w-px bg-amber-100" />
        <div>
          <p className="text-slate-500 text-xs">Sell Signals</p>
          <p className="text-red-600 font-semibold text-lg mt-0.5">
            {counts.SELL} stocks
          </p>
        </div>
        <div className="w-px bg-amber-100" />
        <div>
          <p className="text-slate-500 text-xs">Neutral</p>
          <p className="text-amber-700 font-semibold text-lg mt-0.5">
            {counts.NEUTRAL} stocks
          </p>
        </div>
        <div className="w-px bg-amber-100" />
        <div>
          <p className="text-slate-500 text-xs">Last Computed</p>
          <p className="text-slate-900 font-semibold text-lg mt-0.5">
            24 Mar 2025
          </p>
        </div>
      </div>

      {/* Disclaimer */}
      <div className="flex items-start gap-2 bg-amber-50 border border-amber-200 rounded-lg px-4 py-3">
        <Info size={15} className="text-amber-700 mt-0.5 shrink-0" />
        <p className="text-slate-600 text-xs leading-relaxed">
          Signals are generated by XGBoost and Prophet models using historical
          price data. They are for informational purposes only and do not
          constitute financial advice.
        </p>
      </div>

      {/* Table */}
      <PredictionTable data={mockPredictions} />

    </div>
  );
}