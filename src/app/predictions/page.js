"use client";

import { useState } from "react";
import PredictionTable from "@/components/prediction/PredictionTable";
import RiskInsightCard from "@/components/risk/RiskInsightCard";
import RiskScoreBanner from "@/components/risk/RiskScoreBanner";
import { usePredictions } from "@/hooks/usePredictions";
import { useRisk, useAnalyzeRisk } from "@/hooks/useRisk";
import { Info, RefreshCw } from "lucide-react";
import { Button } from "@/components/ui/button";

function getSignalCounts(data) {
  return data.reduce(
    (acc, s) => {
      acc[s.signal] = (acc[s.signal] || 0) + 1;
      return acc;
    },
    { BUY: 0, SELL: 0, NEUTRAL: 0 }
  );
}

const tabs = ["Signals", "Risk Insights"];

export default function PredictionsPage() {
  const [activeTab, setActiveTab] = useState("Signals");

  const { data: predictions, isLoading: predictionsLoading } = usePredictions();
  const { data: risk, isLoading: riskLoading } = useRisk();
  const analyzeRisk = useAnalyzeRisk();

  const data = predictions || [];
  const counts = getSignalCounts(data);

  const lastComputed = data.length > 0
    ? new Date(data[0].generatedAt).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" })
    : "Not yet";

  return (
    <div className="flex flex-col gap-6">
      {/* Header */}
      <div>
        <h1 className="text-slate-900 text-xl font-semibold mt-4">Predictions</h1>
        <p className="text-slate-500 text-sm mt-1">
          ML-generated signals and risk analysis for your holdings
        </p>
      </div>

      {/* Tabs */}
      <div className="flex gap-1 bg-white border border-amber-200 rounded-lg p-1 w-fit">
        {tabs.map((tab) => (
          <button
            key={tab}
            onClick={() => setActiveTab(tab)}
            className={`px-4 py-1.5 rounded-md text-sm font-medium transition-colors ${activeTab === tab
                ? "bg-slate-900 text-white"
                : "text-slate-600 hover:bg-amber-50 hover:text-amber-700"
              }`}
          >
            {tab}
          </button>
        ))}
      </div>

      {/* SIGNALS TAB */}
      {activeTab === "Signals" && (
        <>
          <div className="bg-white border border-amber-200 rounded-xl px-6 py-4 flex gap-8">
            <div>
              <p className="text-slate-500 text-xs">Buy Signals</p>
              <p className="text-green-600 font-semibold text-lg mt-0.5">{counts.BUY} stocks</p>
            </div>
            <div className="w-px bg-amber-100" />
            <div>
              <p className="text-slate-500 text-xs">Sell Signals</p>
              <p className="text-red-600 font-semibold text-lg mt-0.5">{counts.SELL} stocks</p>
            </div>
            <div className="w-px bg-amber-100" />
            <div>
              <p className="text-slate-500 text-xs">Neutral</p>
              <p className="text-amber-700 font-semibold text-lg mt-0.5">{counts.NEUTRAL} stocks</p>
            </div>
            <div className="w-px bg-amber-100" />
            <div>
              <p className="text-slate-500 text-xs">Last Computed</p>
              <p className="text-slate-900 font-semibold text-lg mt-0.5">{lastComputed}</p>
            </div>
          </div>

          <div className="flex items-start gap-2 bg-amber-50 border border-amber-200 rounded-lg px-4 py-3">
            <Info size={15} className="text-amber-700 mt-0.5 shrink-0" />
            <p className="text-slate-600 text-xs leading-relaxed">
              Signals are generated by XGBoost and Prophet models using historical price data.
              They are for informational purposes only and do not constitute financial advice.
            </p>
          </div>

          {predictionsLoading ? (
            <div className="text-slate-400 text-sm text-center py-8">Loading predictions...</div>
          ) : data.length === 0 ? (
            <div className="text-slate-400 text-sm text-center py-8">
              No predictions yet — they will appear after the ML service runs.
            </div>
          ) : (
            <PredictionTable data={data} />
          )}
        </>
      )}

      {/* RISK INSIGHTS TAB */}
      {activeTab === "Risk Insights" && (
        <>
          <div className="flex justify-end">
            <Button
              className="bg-slate-900 hover:bg-slate-800 text-white text-sm gap-2"
              onClick={() => analyzeRisk.mutate()}
              disabled={analyzeRisk.isPending}
            >
              <RefreshCw size={15} />
              {analyzeRisk.isPending ? "Analyzing..." : "Re-analyze Risk"}
            </Button>
          </div>

          {riskLoading ? (
            <div className="text-slate-400 text-sm text-center py-8">Loading risk analysis...</div>
          ) : !risk ? (
            <div className="text-center py-8 flex flex-col items-center gap-3">
              <p className="text-slate-400 text-sm">No risk analysis yet.</p>
              <Button
                className="bg-slate-900 hover:bg-slate-800 text-white text-sm gap-2"
                onClick={() => analyzeRisk.mutate()}
                disabled={analyzeRisk.isPending}
              >
                <RefreshCw size={15} />
                {analyzeRisk.isPending ? "Analyzing..." : "Run Risk Analysis"}
              </Button>
            </div>
          ) : (
            <>
              <RiskScoreBanner data={risk} />
              <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
                {risk.insights.map((insight, i) => (
                  <RiskInsightCard key={i} insight={insight} />
                ))}
              </div>
            </>
          )}
        </>
      )}
    </div>
  );
}